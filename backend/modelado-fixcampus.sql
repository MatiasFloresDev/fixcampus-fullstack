-- Modelo físico de referencia para PostgreSQL.
-- La aplicación puede crear estas tablas automáticamente con DDL_AUTO=update.
CREATE TABLE IF NOT EXISTS app_user (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(120) NOT NULL, email VARCHAR(180) NOT NULL UNIQUE,
  password_hash VARCHAR(100) NOT NULL, role VARCHAR(20) NOT NULL, active BOOLEAN NOT NULL
);
CREATE TABLE IF NOT EXISTS category (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(100) NOT NULL UNIQUE, description VARCHAR(500), active BOOLEAN NOT NULL
);
CREATE TABLE IF NOT EXISTS area (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(100) NOT NULL UNIQUE, description VARCHAR(500), active BOOLEAN NOT NULL
);
CREATE TABLE IF NOT EXISTS technician (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL UNIQUE REFERENCES app_user(id), specialty VARCHAR(150) NOT NULL, active BOOLEAN NOT NULL
);
CREATE TABLE IF NOT EXISTS report (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, version BIGINT,
  title VARCHAR(160) NOT NULL, description VARCHAR(5000) NOT NULL, location VARCHAR(200) NOT NULL,
  category_id BIGINT NOT NULL REFERENCES category(id), area_id BIGINT NOT NULL REFERENCES area(id),
  reporter_id BIGINT NOT NULL REFERENCES app_user(id), technician_id BIGINT REFERENCES technician(id),
  priority VARCHAR(20) NOT NULL, status VARCHAR(20) NOT NULL,
  created_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL, resolved_at TIMESTAMPTZ, closed_at TIMESTAMPTZ
);
CREATE TABLE IF NOT EXISTS report_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, report_id BIGINT NOT NULL REFERENCES report(id),
  actor_id BIGINT NOT NULL REFERENCES app_user(id), from_status VARCHAR(20), to_status VARCHAR(20) NOT NULL,
  note VARCHAR(2000), created_at TIMESTAMPTZ NOT NULL
);
CREATE TABLE IF NOT EXISTS notification_log (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, report_id BIGINT NOT NULL REFERENCES report(id),
  recipient VARCHAR(180) NOT NULL, status VARCHAR(30) NOT NULL, detail VARCHAR(1000), created_at TIMESTAMPTZ NOT NULL
);
CREATE TABLE IF NOT EXISTS report_comment (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, report_id BIGINT NOT NULL REFERENCES report(id),
  author_id BIGINT NOT NULL REFERENCES app_user(id), body VARCHAR(2000) NOT NULL, created_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_report_comment_report ON report_comment(report_id);
